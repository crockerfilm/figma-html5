// Builds the plugin panel (ui.html) from src/ui.html, inlining the converter
// (src/converter.js) and stamping the version (../VERSION). Run after changing
// any of them:
//
//   node figma-plugin/build.mjs
//
// Figma loads ui.html as one self-contained file (no network, no imports), so
// the converter has to be copied in rather than referenced.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const converter = readFileSync(join(here, "src", "converter.js"), "utf8");
// The version, shown in the panel's footer so people can tell if theirs is current.
const version = readFileSync(join(here, "..", "VERSION"), "utf8").trim();

const src = readFileSync(join(here, "src", "ui.html"), "utf8");
const slot = "/* @converter */";
if (!src.includes(slot)) throw new Error(`src/ui.html is missing the ${slot} placeholder`);

// Wrapped so the web tool's names can't collide with the panel's own.
const inlined = `const Converter = (() => {
${converter}
return { run, SPEC, makeZip, makeBackup, kb, fmt, matMul, matInvert, parseTransform };
})();`;

writeFileSync(join(here, "ui.html"),
  "<!-- Generated by build.mjs from src/ui.html and src/converter.js. Edit those, then rebuild. -->\n" +
  src.replace(slot, () => inlined).replace(/__VERSION__/g, version));
console.log(`ui.html built — v${version}, converter ${(converter.length / 1024).toFixed(0)} KB inlined`);
